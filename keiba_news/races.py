def _variants(name: str) -> set[str]:
    out = {name}
    pairs = [("ステークス", "S"), ("カップ", "C")]
    for long, short in pairs:
        for v in list(out):
            if v.endswith(long):
                out.add(v[: -len(long)] + short)
    return out


def build_race_patterns() -> list[tuple[str, str, str]]:
    """(見出し中の表記, 正式名, グレード) を長い表記順に返す。"""
    rows: list[tuple[str, str, str]] = []
    for name, grade, aliases in GRADED_RACES:
        for base in [name, *aliases]:
            for v in _variants(base):
                rows.append((v, name, grade))
    rows.sort(key=lambda r: len(r[0]), reverse=True)
    return rows
